#!/usr/bin/env python3
"""Install the supplied Alpha 2 as a private, loopback-only user service.

Run on the destination Linux server as its regular owner, not as root.
Default mode is a read-only preflight. --install explicitly performs installation.
No firewall changes, cloud resources, SSH keys, or public listener are created.
"""
from __future__ import annotations
import argparse
import hashlib
import http.client
import json
import os
from pathlib import Path, PurePosixPath
import shutil
import socket
import stat
import subprocess
import sys
import tempfile
import time
import zipfile

from checkout import read_checkout, stage_checkout

SOURCE_SHA256 = '7d4482b51ca31b4355c1364a3e87cacefcab7689a443cab75ea9dd66553e7aa1'
SERVICE = 'eksmu-private.service'
MAX_EXPANDED = 32 * 1024 * 1024


def validate_archive(archive: Path) -> None:
    if hashlib.sha256(archive.read_bytes()).hexdigest() != SOURCE_SHA256:
        raise ValueError('Source archive digest mismatch; no files installed.')
    total = 0
    with zipfile.ZipFile(archive) as package:
        for item in package.infolist():
            path = PurePosixPath(item.filename)
            if (path.is_absolute() or '..' in path.parts or not path.parts
                    or path.parts[0] != 'open-inquiry-community'
                    or '\\' in item.filename
                    or stat.S_ISLNK(item.external_attr >> 16)):
                raise ValueError('Unsafe source archive path.')
            total += item.file_size
        if total > MAX_EXPANDED:
            raise ValueError('Source archive exceeds expected unpacked size.')


def safe_root(root: Path, home: Path) -> Path:
    root = root.absolute()
    if any(c in str(root) for c in '\n\r\x00%$\\"'):
        raise ValueError('Unsupported characters in installation path.')
    home = home.resolve()
    if not root.resolve().is_relative_to(home) or root.resolve() == home:
        raise ValueError('Use a new directory below your home directory.')
    if root.exists() or root.is_symlink():
        raise ValueError('Installation directory already exists; nothing will be overwritten.')
    return root


def service_text(root: Path, port: int, module: str = 'eksmu') -> str:
    # The pinned Alpha 2 archive predates the rename and ships the package as ``eksmu``.
    return f'''# Eksmu private service; generated by install.py
[Unit]
Description=Eksmu private instance
After=network.target
StartLimitIntervalSec=60
StartLimitBurst=5

[Service]
Type=simple
WorkingDirectory={root}/app
ExecStart="{root}/venv/bin/python" -m {module} --db "{root}/data/community.sqlite" serve --port {port}
Environment=PYTHONUNBUFFERED=1
Environment=PYTHONDONTWRITEBYTECODE=1
Environment=OMP_NUM_THREADS=1
Environment=OPENBLAS_NUM_THREADS=1
UMask=0077
Restart=on-failure
RestartSec=3
TimeoutStopSec=20
NoNewPrivileges=true
Nice=10
CPUQuota=50%
MemoryMax=1G
TasksMax=64

[Install]
WantedBy=default.target
'''


def run(*args: str, **kwargs) -> subprocess.CompletedProcess:
    return subprocess.run(list(args), check=True, **kwargs)


def check_port(port: int) -> None:
    with socket.socket() as sock:
        sock.bind(('127.0.0.1', port))


def health(port: int, timeout: float = 15) -> bool:
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        conn = http.client.HTTPConnection('127.0.0.1', port, timeout=2)
        try:
            conn.request('GET', '/api/health')
            response = conn.getresponse()
            body = json.loads(response.read())
            if response.status == 200 and body.get('mode') == 'local-private-prototype':
                return True
        except (OSError, ValueError, http.client.HTTPException):
            pass
        finally:
            conn.close()
        time.sleep(.4)
    return False


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--install', action='store_true', help='Create venv, install dependencies and start the user service')
    parser.add_argument('--root', type=Path, default=Path.home()/'.local/share/eksmu-private')
    parser.add_argument('--port', type=int, default=8765)
    source = parser.add_mutually_exclusive_group()
    source.add_argument('--source-dir', type=Path, help='Use a checked-out repository (default)')
    source.add_argument('--source-archive', type=Path, help='Use the original SHA-256 pinned Alpha 2 archive')
    args = parser.parse_args()
    if sys.version_info < (3, 11):
        parser.error('Python 3.11 or newer is required; choose an installed python3.11+ interpreter.')
    if sys.platform != 'linux' or os.geteuid() == 0:
        parser.error('Run as the regular server user on Linux, not as root.')
    if not 1024 <= args.port <= 65535:
        parser.error('Choose a port from 1024 to 65535.')
    os.umask(0o077)
    archive = args.source_archive
    files = None
    if archive is not None:
        validate_archive(archive)
        provenance = {'type': 'original_archive', 'sha256': SOURCE_SHA256}
    else:
        source_root = args.source_dir or Path(__file__).resolve().parents[2]
        manifest = Path(__file__).with_name('source-manifest.json')
        files = read_checkout(source_root, manifest)
        provenance = {'type': 'checked_out_source', 'files': len(files),
                      'manifest_sha256': hashlib.sha256(manifest.read_bytes()).hexdigest()}
    root = safe_root(args.root, Path.home())
    unit = Path.home()/'.config/systemd/user'/SERVICE
    if unit.exists() or unit.is_symlink():
        raise ValueError('A service with this name already exists; refusing to replace it.')
    check_port(args.port)
    if not shutil.which('systemctl'):
        raise ValueError('This installer requires systemd user services.')
    run('systemctl', '--user', 'show-environment', stdout=subprocess.DEVNULL, stderr=subprocess.PIPE)
    try:
        linger = run('loginctl', 'show-user', str(os.getuid()), '-p', 'Linger', '--value',
                     capture_output=True, text=True).stdout.strip() == 'yes'
    except (subprocess.CalledProcessError, OSError):
        linger = False
    preflight = {'source_digest_verified': True, 'source': provenance, 'root': str(root), 'port': args.port,
                 'listener': '127.0.0.1', 'pandoc_available': bool(shutil.which('pandoc')),
                 'user_linger_enabled': linger, 'remote_changes': False}
    print(json.dumps(preflight, ensure_ascii=False, indent=2), flush=True)
    if not args.install:
        print('Preflight only. Add --install to install. No server files changed.')
        return 0
    if not linger:
        raise ValueError('Enable user lingering first (administrator: loginctl enable-linger $USER), then rerun. No install performed.')

    root.mkdir(parents=True, mode=0o700)
    unit_created = False
    try:
        if files is not None:
            stage_checkout(files, root/'app')
        else:
            with tempfile.TemporaryDirectory(prefix='unpack-', dir=root) as temp:
                with zipfile.ZipFile(archive) as package:
                    package.extractall(temp)
                shutil.move(str(Path(temp)/'open-inquiry-community'), str(root/'app'))
        (root/'data').mkdir(mode=0o700)
        run(sys.executable, '-m', 'venv', str(root/'venv'))
        python = str(root/'venv/bin/python')
        run(python, '-m', 'pip', 'install', '--disable-pip-version-check',
            '-r', str(root/'app/requirements-research.txt'), timeout=300)
        run(python, str(root/'app/scripts/doctor.py'), timeout=15)
        module = 'eksmu' if files is None else 'eksmu'
        run(python, '-c', f'import PIL, cryptography; import {module}.community, {module}.research',
            cwd=root/'app', timeout=15)
        check_port(args.port)
        unit.parent.mkdir(parents=True, exist_ok=True)
        with unit.open('x', encoding='utf-8') as out:
            out.write(service_text(root, args.port, module))
        unit_created = True
        run('systemctl', '--user', 'daemon-reload')
        run('systemctl', '--user', 'enable', '--now', SERVICE)
        if not health(args.port):
            raise RuntimeError('Private service health check failed.')
        status = {'installed': True, 'service': SERVICE, 'listen': f'127.0.0.1:{args.port}',
                  'source': provenance, 'public_site': False,
                  'installed_at_utc': time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime())}
        (root/'deployment.json').write_text(json.dumps(status, indent=2)+'\n')
        print(json.dumps(status, ensure_ascii=False, indent=2))
        print(f'Use SSH forwarding to access the service; do not open port {args.port} in a public firewall.')
        return 0
    except BaseException:
        # Affect only the service created by this run; retain files/logs for diagnosis.
        if unit_created:
            subprocess.run(['systemctl','--user','disable','--now',SERVICE], check=False,
                           stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
            unit.unlink(missing_ok=True)
            subprocess.run(['systemctl','--user','daemon-reload'],check=False,
                           stdout=subprocess.DEVNULL,stderr=subprocess.DEVNULL)
        print(f'Installation failed. No existing project was replaced. New staging directory retained: {root}', file=sys.stderr)
        raise


if __name__ == '__main__':
    try:
        raise SystemExit(main())
    except (OSError, ValueError, RuntimeError, subprocess.SubprocessError) as exc:
        print(f'ERROR: {exc}', file=sys.stderr)
        raise SystemExit(1)
