#!/usr/bin/env python3
"""Prepare an isolated Eksmu public Alpha candidate; never activate it.

Default: read-only preflight. --stage copies only the manifest-verified runtime
into a NEW private directory below the operator's home. It writes candidate
systemd/nginx configuration there, without touching /etc, services, DNS,
firewalls, the private 8765 installation, databases, certificates or credentials.
Python 3.11+ and a regular Linux user are required.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import socket
import stat
import sys

from checkout import read_checkout, stage_checkout

SERVICE = 'eksmu-web.service'
DOMAIN = 'eksmu.com'
PORT = 8780
CERT_PLACEHOLDER = Path('/REPLACE_WITH_TRUSTED_EKSMU_CERT/fullchain.pem')
KEY_PLACEHOLDER = Path('/REPLACE_WITH_TRUSTED_EKSMU_CERT/privkey.pem')


def config_path(path: Path) -> Path:
    """Reject nginx/systemd interpolation, directives, traversal and whitespace."""
    value = str(path)
    if (not path.is_absolute() or not re.fullmatch(r'/[A-Za-z0-9_./-]+', value)
            or '..' in path.parts or path.as_posix() != value):
        raise ValueError('Use an absolute path containing only letters, digits, /, _, ., and -.')
    return path


def new_root(root: Path, home: Path) -> Path:
    root = config_path(root.absolute())
    home = home.resolve(strict=True)
    if root == home or not root.is_relative_to(home):
        raise ValueError('Candidate root must be a NEW directory below your home.')
    for ancestor in (root, *root.parents):
        if ancestor == home:
            break
        if ancestor.is_symlink():
            raise ValueError('Symlinked candidate paths are refused.')
    if root.exists():
        raise ValueError('Candidate root exists; no files or data will be replaced.')
    return root


def mail_file(path: Path, home: Path, root: Path, source: Path) -> bool:
    path = config_path(path)
    home = home.resolve(strict=True)
    if not path.is_relative_to(home) or path.is_relative_to(root) or path.is_relative_to(source):
        raise ValueError('mail.env must be external to the candidate/source, below your home.')
    for ancestor in (path, *path.parents):
        if ancestor == home:
            break
        if ancestor.is_symlink():
            raise ValueError('Symlinked mail.env paths are refused.')
    if not path.exists():
        return False
    metadata = path.stat()
    if (not stat.S_ISREG(metadata.st_mode) or stat.S_IMODE(metadata.st_mode) != 0o600
            or metadata.st_uid != os.getuid()):
        raise ValueError('Existing mail.env must be a regular, owner-controlled 0600 file.')
    # Never read, copy or print its values.
    return True


def tls_paths(certificate: Path | None, key: Path | None) -> tuple[Path, Path, bool]:
    if (certificate is None) != (key is None):
        raise ValueError('Supply both --tls-certificate and --tls-key, or neither.')
    if certificate is None:
        return CERT_PLACEHOLDER, KEY_PLACEHOLDER, False
    certificate, key = config_path(certificate), config_path(key)
    if not certificate.is_file() or not key.is_file():
        raise ValueError('Explicit TLS paths must refer to existing files; no keys are copied.')
    return certificate, key, True


def service_text(root: Path, env_file: Path) -> str:
    root, env_file = config_path(root), config_path(env_file)
    return f'''# CANDIDATE ONLY: generated by public_alpha.py; not installed or started.
[Unit]
Description=Eksmu independent public Alpha backend
After=network.target
StartLimitIntervalSec=60
StartLimitBurst=5

[Service]
Type=simple
WorkingDirectory={root}/app
ExecStart="{root}/venv/bin/python" -m eksmu --db "{root}/data/community.sqlite" serve --port {PORT} --public-origin https://{DOMAIN}
EnvironmentFile=-{env_file}
Environment=PYTHONUNBUFFERED=1
Environment=PYTHONDONTWRITEBYTECODE=1
Environment=OMP_NUM_THREADS=1
Environment=OPENBLAS_NUM_THREADS=1
UMask=0077
Restart=on-failure
RestartSec=3
TimeoutStopSec=20
NoNewPrivileges=true
Nice=10
CPUQuota=50%
MemoryMax=1G
TasksMax=64

[Install]
WantedBy=default.target
'''


def _port(port: int) -> int:
    if type(port) is not int or not 1 <= port <= 65535:
        raise ValueError('Invalid configuration port.')
    return port


def _proxy_location(path: str, backend_port: int, *, auth: bool = False,
                    client_max_body_size: str | None = None,
                    timeout: int = 30) -> str:
    auth_limits = '''        limit_req zone=eksmu_alpha_auth_post_ip burst=5 nodelay;
        limit_req zone=eksmu_alpha_auth_post_site burst=20 nodelay;
''' if auth else ''
    body_limit = f'''        client_max_body_size {client_max_body_size};
''' if client_max_body_size else ''
    # All auth locations repeat the site limit: nginx does not inherit it when
    # a location supplies its own limit_req directives.
    return f'''    location {path} {{
{body_limit}        limit_req zone=eksmu_alpha_requests burst=300 nodelay;
{auth_limits}        proxy_pass http://127.0.0.1:{_port(backend_port)};
        proxy_http_version 1.1;
        proxy_set_header Host {DOMAIN};
        proxy_set_header X-Eksmu-Client-IP $remote_addr;
        proxy_set_header Forwarded "";
        proxy_set_header X-Forwarded-For "";
        proxy_set_header X-Forwarded-Host "";
        proxy_set_header X-Forwarded-Proto "";
        proxy_set_header X-Real-IP "";
        proxy_set_header X-Eksmu-Direct-Peer-Only "";
        proxy_set_header Connection "";
        proxy_cache off;
        proxy_next_upstream off;
        proxy_connect_timeout 3s;
        proxy_send_timeout {int(timeout)}s;
        proxy_read_timeout {int(timeout)}s;
    }}
'''


def http_server(acme_root: Path, *, port: int = 80, bind_loopback: bool = False,
                redirect: bool = True) -> str:
    acme_root = config_path(acme_root)
    listen = ('127.0.0.1:' if bind_loopback else '') + str(_port(port))
    fallback = f'301 https://{DOMAIN}$request_uri' if redirect else '503'
    return f'''server {{
    listen {listen};
    server_name {DOMAIN};
    access_log off;
    error_log /dev/null crit;
    if ($host != {DOMAIN}) {{ return 421; }}
    location ^~ /.well-known/acme-challenge/ {{
        root {acme_root};
        default_type text/plain;
        try_files $uri =404;
    }}
    location / {{ return {fallback}; }}
}}
'''


def nginx_text(certificate: Path, key: Path, acme_root: Path, *, backend_port: int = PORT,
               https_port: int = 443, http_port: int = 80, bind_loopback: bool = False,
               static_cache: Path = Path('/var/cache/nginx/eksmu_static'),
               peer_connections: int = 16, site_connections: int = 512) -> str:
    """http-context include; alternate sockets and cache directory are for isolated parser/HTTP tests."""
    certificate, key, acme_root, static_cache = map(config_path, (certificate, key, acme_root, static_cache))
    listen = ('127.0.0.1:' if bind_loopback else '') + str(_port(https_port))
    return f'''# CANDIDATE: include only within nginx http {{}} after independent review.
# Do not replace the existing IP/default site. No default_server directive.
# Domain-specific real_ip settings override inherited TCP proxy trust.
# REPLACE_WITH_TRUSTED_EKSMU_CERT paths are unusable placeholders.
# Strict auth limits count only POST credential/code submissions, matching the
# application limiter; empty keys are not accounted, so status/profile reads
# after each step stay under the site-wide limit instead of locking users out.
# Zone names must change whenever a key changes: nginx rejects a reload that
# reuses a zone name with a different key and keeps running the old config.
map $request_method $eksmu_alpha_auth_peer {{ POST $binary_remote_addr; default ""; }}
map $request_method $eksmu_alpha_auth_site {{ POST $server_name; default ""; }}
limit_req_zone $server_name zone=eksmu_alpha_requests:1m rate=300r/s;
limit_req_zone $eksmu_alpha_auth_peer zone=eksmu_alpha_auth_post_ip:1m rate=6r/m;
limit_req_zone $eksmu_alpha_auth_site zone=eksmu_alpha_auth_post_site:1m rate=60r/m;
limit_conn_zone $binary_remote_addr zone=eksmu_alpha_connections_ip:1m;
limit_conn_zone $server_name zone=eksmu_alpha_connections_total:1m;
proxy_cache_path {static_cache} levels=1 keys_zone=eksmu_static:2m max_size=64m inactive=10m use_temp_path=off;

{http_server(acme_root, port=http_port, bind_loopback=bind_loopback)}
server {{
    listen {listen} ssl;
    server_name {DOMAIN};
    ssl_certificate {certificate};
    ssl_certificate_key {key};
    ssl_protocols TLSv1.2 TLSv1.3;
    ssl_session_cache shared:eksmu_alpha_tls:1m;
    ssl_session_timeout 10m;
    access_log off;
    error_log /dev/null crit;
    server_tokens off;
    # This server has TCP listeners only, so no peer matches unix: trust.
    set_real_ip_from unix:;
    real_ip_header X-Eksmu-Direct-Peer-Only;
    real_ip_recursive off;
    if ($host != {DOMAIN}) {{ return 421; }}
    client_max_body_size 8m;
    client_header_timeout 10s;
    client_body_timeout 15s;
    keepalive_timeout 15s;
    send_timeout 30s;
    limit_req_status 429;
    limit_conn_status 429;
    limit_conn eksmu_alpha_connections_ip {int(peer_connections)};
    limit_conn eksmu_alpha_connections_total {int(site_connections)};
{_proxy_location('^~ /api/auth/', backend_port, auth=True)}
{_proxy_location('= /api/research/upload', backend_port, client_max_body_size='48m', timeout=120)}
{_proxy_location('= /api/research/inspect-source', backend_port, client_max_body_size='48m', timeout=120)}
    # Static scripts, styles and icons (top-level files and /i18n/<lang>.js): nginx keeps them
    # for 60 s so a page view costs the Python backend only its HTML and API calls. Browsers
    # still get no-store from the app; a deploy is visible within a minute.
    location ~ "^/(?:[A-Za-z0-9_.-]+\.(?:js|css|svg)|i18n/[a-z]{{2}}\.js|fonts/[A-Za-z0-9_.-]+\.woff2)$" {{
        limit_req zone=eksmu_alpha_requests burst=300 nodelay;
        proxy_pass http://127.0.0.1:{_port(backend_port)};
        proxy_http_version 1.1;
        proxy_set_header Host {DOMAIN};
        proxy_set_header X-Eksmu-Client-IP $remote_addr;
        proxy_set_header Forwarded "";
        proxy_set_header X-Forwarded-For "";
        proxy_set_header X-Forwarded-Host "";
        proxy_set_header X-Forwarded-Proto "";
        proxy_set_header X-Real-IP "";
        proxy_set_header X-Eksmu-Direct-Peer-Only "";
        proxy_set_header Connection "";
        proxy_set_header Cookie "";
        proxy_cache eksmu_static;
        proxy_cache_key $uri;
        proxy_cache_valid 200 60s;
        proxy_cache_lock on;
        proxy_cache_use_stale updating error timeout;
        proxy_ignore_headers Cache-Control Expires Set-Cookie;
        proxy_hide_header Set-Cookie;
        proxy_next_upstream off;
        proxy_connect_timeout 3s;
        proxy_send_timeout 30s;
        proxy_read_timeout 30s;
    }}
{_proxy_location('/', backend_port)}}}
'''


def operator_notes(root: Path, env_file: Path, tls_explicit: bool) -> str:
    return f'''# Eksmu public Alpha candidate — staged, NOT live

This independent candidate has an empty data directory and a manifest-verified
runtime. The private 8765 installation and every existing database remain intact.
No venv/dependencies, service, nginx include, certificate, DNS or firewall was
installed/changed. The candidate backend is always 127.0.0.1:{PORT}.

Artifacts: app/, data/, {SERVICE}, nginx-https.conf, nginx-acme.conf,
source-manifest.json, candidate.json. Do not point nginx at private 8765.

SMTP: EnvironmentFile=-{env_file} is OPTIONAL and references a separately kept
owner-controlled 0600 file outside this candidate/source. Its contents were not
read or copied. Configure EKSMU_SMTP_HOST, EKSMU_SMTP_FROM, EKSMU_SMTP_USER and
EKSMU_SMTP_PASSWORD_FILE privately; that last file is a separate private credential.
EKSMU_SMTP_PORT defaults to 465; 587 uses STARTTLS. Never add these values to Git.
The public mode requires email confirmation. With no sender configuration the
candidate permits browsing but registration returns 503. File presence alone
does not prove SMTP is configured or that real verification/reset mail works.
Review inherited systemd user-manager environment before activating this unit.

TLS paths explicitly supplied: {str(tls_explicit).lower()}. Existing paths were
only checked for existence/safe syntax, not certificate validity or trust; no
private key was read or copied. Without explicit paths, nginx-https.conf contains
clearly marked unusable certificate placeholders. nginx-acme.conf is an HTTP-only
bootstrap candidate (other paths return 503), not a functioning HTTPS website.
The ACME root is an external operator-managed readable directory; staging does
not create it or change directory permissions. Never install both candidate
nginx configurations together. Review existing listen/default/IP sites. The
domain server overrides inherited real_ip trust to unix: only, while it listens
on TCP, so $remote_addr remains the direct network peer. This requires nginx's
http_realip module, present on the checked nginx 1.18 VM. Recheck modules on a new
host. This candidate overwrites X-Eksmu-Client-IP and removes external
Forwarded/X-Forwarded-* headers. It creates no CDN/proxy trust relationship.

If the target host's port 443 also serves any other default or management virtual
host, an exact server_name block alone does NOT restrict access to that default
site. Before opening port 443 publicly, verify that any other virtual hosts on
the machine enforce their own ingress or source-address restrictions. Keep
private source-IP values outside Git. This preparer never changes nginx,
iptables, cloud firewall rules or source access restrictions.

Activation is separate work: install dependencies in {root}/venv, check the
candidate with systemd-analyze and an independent nginx -t, retain backup/rollback,
then install only the dedicated service and reviewed domain include. Keep the
backend loopback-only. Validate DNS, a trusted eksmu.com certificate, exact origin
and Secure cookies, real mail registration/login/reset, two-author publication,
restore and operational response before calling the service publicly launched.
No staged artifact or local self-signed parser test satisfies these checks.

Limits: auth POST 6 requests/minute per peer (burst 5), 60/minute for this site
(burst 20; auth GET reads use the site limit), all proxied requests 300/second (burst 300), 16 active requests per peer and
512 across this site (raised 2026-11-01 before publicity: 32 let a few slow PDF
downloads block the whole site), body 8 MiB, bounded timeouts. These are initial operational
limits, not identity-based academic publication gates. nginx limit_conn counts
requests only after their complete headers arrive; incomplete headers remain
subject to timeouts and nginx's global worker limits. Access logs are disabled;
site URL error logs are suppressed to avoid recording private query strings.

Official directive references, checked 2026-10-06:
- https://nginx.org/en/docs/http/ngx_http_proxy_module.html#proxy_set_header
- https://nginx.org/en/docs/http/ngx_http_limit_req_module.html
- https://nginx.org/en/docs/http/ngx_http_limit_conn_module.html
- https://nginx.org/en/docs/http/ngx_http_core_module.html#client_max_body_size
- https://nginx.org/en/docs/http/ngx_http_realip_module.html
- https://github.com/systemd/systemd/blob/v249/man/systemd.exec.xml
- https://docs.cloud.google.com/firewall/docs/firewalls
'''


def prepare(source: Path, manifest: Path, root: Path, home: Path, env_file: Path,
            certificate: Path | None = None, key: Path | None = None,
            acme_root: Path = Path('/var/lib/letsencrypt/eksmu'), *, stage: bool = False,
            probe_port: int = PORT) -> dict:
    """probe_port only lets tests check the occupied-port refusal while a live backend owns PORT."""
    source = source.resolve(strict=True)
    manifest_bytes = manifest.read_bytes()
    files = read_checkout(source, manifest)
    if manifest.read_bytes() != manifest_bytes:
        raise ValueError('Source manifest changed during preflight; rerun against a stable snapshot.')
    root = new_root(root, home)
    if root.is_relative_to(source):
        raise ValueError('Candidate must be outside the source checkout.')
    env_exists = mail_file(env_file, home, root, source)
    certificate, key, tls_explicit = tls_paths(certificate, key)
    config_path(acme_root)
    installed_unit = home / '.config/systemd/user' / SERVICE
    if installed_unit.exists() or installed_unit.is_symlink():
        raise ValueError('Dedicated public service already exists; refusing an accidental replacement.')
    with socket.socket() as probe:
        probe.bind(('127.0.0.1', _port(probe_port)))
    record = {
        'format': 'eksmu.public-alpha-candidate.v1', 'root': str(root),
        'service': SERVICE, 'backend': f'127.0.0.1:{PORT}', 'public_origin': f'https://{DOMAIN}',
        'source_files': len(files), 'source_manifest_sha256': hashlib.sha256(manifest_bytes).hexdigest(),
        'mail_env_present': env_exists, 'tls_paths_explicit': tls_explicit,
        'smtp_delivery_verified': False, 'dns_verified': False, 'trusted_tls_verified': False,
        'existing_management_ingress_review_required': True,
        'staged': False, 'public_site': False, 'services_changed': False, 'existing_data_changed': False,
    }
    if not stage:
        return record
    previous_mask = os.umask(0o077)
    try:
        root.mkdir(parents=True, mode=0o700)
        stage_checkout(files, root / 'app')
        (root / 'data').mkdir(mode=0o700)
        outputs = {
            SERVICE: service_text(root, env_file),
            'nginx-https.conf': nginx_text(certificate, key, acme_root),
            'nginx-acme.conf': '# CANDIDATE HTTP bootstrap only; NOT a launched site.\n' + http_server(acme_root, redirect=False),
            'source-manifest.json': manifest_bytes.decode('utf-8'),
            'OPERATOR.md': operator_notes(root, env_file, tls_explicit),
        }
        for name, content in outputs.items():
            with (root / name).open('x', encoding='utf-8') as target:
                target.write(content)
        record['staged'] = True
        with (root / 'candidate.json').open('x', encoding='utf-8') as target:
            json.dump(record, target, indent=2)
            target.write('\n')
    finally:
        os.umask(previous_mask)
    return record


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--stage', action='store_true', help='Write a new private candidate; never install/start it')
    parser.add_argument('--source-dir', type=Path, default=Path(__file__).resolve().parents[2])
    parser.add_argument('--root', type=Path, default=Path.home() / '.local/share/eksmu-web')
    parser.add_argument('--mail-env', type=Path, default=Path.home() / '.config/eksmu/mail.env')
    parser.add_argument('--tls-certificate', type=Path)
    parser.add_argument('--tls-key', type=Path)
    parser.add_argument('--acme-root', type=Path, default=Path('/var/lib/letsencrypt/eksmu'))
    args = parser.parse_args()
    if sys.version_info < (3, 11) or sys.platform != 'linux' or os.geteuid() == 0:
        parser.error('Run as a regular Linux server user with Python 3.11+, not root.')
    record = prepare(args.source_dir, Path(__file__).with_name('source-manifest.json'), args.root,
                     Path.home(), args.mail_env, args.tls_certificate, args.tls_key,
                     args.acme_root, stage=args.stage)
    print(json.dumps(record, ensure_ascii=False, indent=2))
    print('Candidate staged; NOT live. Read OPERATOR.md.' if args.stage
          else 'Read-only preflight; no server files changed. Add --stage to prepare a candidate.')
    return 0


if __name__ == '__main__':
    try:
        raise SystemExit(main())
    except (OSError, ValueError) as exc:
        print(f'ERROR: {exc}', file=sys.stderr)
        raise SystemExit(1)
